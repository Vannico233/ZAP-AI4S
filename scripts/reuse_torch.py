"""Copy the already installed Torch dependency tree into the project venv, offline."""
import argparse
import csv
import importlib.metadata as metadata
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import sysconfig


def protected(name):
    return name in {"torch", "torchvision", "triton"} or name.startswith(("nvidia-", "cuda-"))


def dependency_plan(names=("torch", "torchvision")):
    try:
        from packaging.requirements import Requirement
        from packaging.utils import canonicalize_name
    except ImportError:
        from pip._vendor.packaging.requirements import Requirement
        from pip._vendor.packaging.utils import canonicalize_name
    packages = {}
    pending = [Requirement(name) for name in names]
    while pending:
        requirement = pending.pop()
        if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
            continue
        dist = metadata.distribution(requirement.name)
        name = canonicalize_name(dist.metadata["Name"])
        if not requirement.specifier.contains(dist.version, prereleases=True):
            raise RuntimeError(f"Source dependency mismatch: {requirement}, installed {dist.version}")
        if name in packages:
            continue
        root = Path(dist.locate_file("")).resolve()
        if not root.is_relative_to(Path(sys.prefix).resolve()):
            raise RuntimeError(f"Source package is outside its environment: {name}: {root}")
        files = []
        for entry in dist.files or []:
            relative = PurePosixPath(str(entry).replace("\\", "/"))
            # Entry point scripts are regenerated/used via python -m, never copied
            # with their old interpreter paths. Ignore generated bytecode as well.
            if relative.is_absolute() or ".." in relative.parts or "__pycache__" in relative.parts:
                continue
            if relative.suffix == ".pyc":
                continue
            digest = f"{entry.hash.mode}={entry.hash.value}" if entry.hash else ""
            files.append([str(relative), digest, entry.size])
        if not files:
            raise RuntimeError(f"No installed file manifest for {name}")
        packages[name] = {"version": dist.version, "root": str(root), "files": files}
        pending.extend(Requirement(value) for value in dist.requires or [])
    return packages


def check_stack():
    import torch
    import torchvision
    if (torch.__version__, torchvision.__version__, torch.version.cuda) != (
            "2.10.0+cu128", "0.25.0+cu128", "12.8"):
        raise RuntimeError(f"Expected Torch 2.10.0+cu128 / torchvision 0.25.0+cu128; "
                           f"found {torch.__version__} / {torchvision.__version__}, CUDA {torch.version.cuda}")
    # This works on the CPU preparation instance and checks the paired C++ extensions.
    torchvision.ops.nms(torch.tensor([[0., 0., 1., 1.]]), torch.tensor([1.]), 0.5)
    return dependency_plan()


def safe_path(root, relative):
    # Callers resolve the environment root once, before iterating its files.
    root = Path(root)
    relative = PurePosixPath(relative)
    if relative.is_absolute() or ".." in relative.parts or not relative.parts:
        raise ValueError(f"Unsafe package path: {relative}")
    result = (root / str(relative)).resolve()
    if not result.is_relative_to(root):
        raise ValueError(f"Package path leaves its environment: {relative}")
    return result


def copy_packages(packages, target):
    """Make independent copies; never hard-link or expose the source site-packages."""
    target = Path(target).resolve()
    target.mkdir(parents=True, exist_ok=True)
    installed = {d.metadata["Name"].lower().replace("_", "-"): d.version
                 for d in metadata.distributions(path=[str(target)])}
    jobs = []
    total = 0
    print("Checking local package files and available disk space...", flush=True)
    for name, package in packages.items():
        if name in installed and installed[name] != package["version"]:
            if protected(name):
                raise RuntimeError(f"Project already has a different {name}: {installed[name]}")
            # Keep project-specific upgrades/downgrades of ordinary dependencies.
            continue
        root = Path(package["root"]).resolve()
        files = []
        for relative, digest, size in package["files"]:
            source = safe_path(root, relative)
            destination = safe_path(target, relative)
            if not source.is_file():
                raise FileNotFoundError(f"Missing source package file: {source}")
            if source == destination:
                raise ValueError("Source and project package paths must differ")
            total += source.stat().st_size
            files.append((source, destination, relative, digest, size))
        jobs.append((name, package["version"], files))
    if shutil.disk_usage(target).free < total:
        raise RuntimeError(f"Local Torch copy needs up to {total / 2**30:.1f} GiB free in {target}")
    print(f"Copying {len(jobs)} installed packages locally (up to {total / 2**30:.1f} GiB); no downloads.", flush=True)
    for name, version, files in jobs:
        print(f"  {name}=={version}", flush=True)
        # Publish METADATA last so an interrupted package copy isn't treated as installed.
        for source, destination, relative, digest, size in sorted(files, key=lambda f: f[0].name == "METADATA"):
            if source.name == "RECORD" and source.parent.name.endswith(".dist-info"):
                continue
            destination.parent.mkdir(parents=True, exist_ok=True)
            temporary = destination.with_name(destination.name + ".zap-copying")
            try:
                shutil.copy2(source, temporary)
                os.replace(temporary, destination)
            finally:
                if temporary.exists():
                    temporary.unlink()
        # Omit source-only executable paths from the installed RECORD.
        for source, destination, *_ in files:
            if source.name == "RECORD" and source.parent.name.endswith(".dist-info"):
                temporary = destination.with_name(destination.name + ".zap-copying")
                with temporary.open("w", newline="", encoding="utf-8") as record:
                    csv.writer(record).writerows((rel, digest, size) for _, _, rel, digest, size in files)
                os.replace(temporary, destination)


def probe(python, describe=False):
    result = subprocess.run([str(python), str(Path(__file__).resolve()),
                             "--describe" if describe else "--check"],
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or "Torch environment check failed")
    return json.loads(result.stdout)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-python", default=getattr(sys, "_base_executable", sys.executable))
    parser.add_argument("--describe", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.describe or args.check:
        packages = check_stack()
        result = {"python": list(sys.version_info[:2]), "platform": sys.platform,
                  "source": sys.prefix, "packages": packages if args.describe else
                  {name: info["version"] for name, info in packages.items()}}
        print(json.dumps(result))
        return
    if sys.prefix == sys.base_prefix:
        raise RuntimeError("Run this script with the project's virtual environment Python")
    try:
        current = probe(sys.executable)
        print("Project Torch/CUDA is already complete; skipping copy.")
    except RuntimeError:
        source = probe(args.source_python, describe=True)
        if source["python"] != list(sys.version_info[:2]) or source["platform"] != sys.platform:
            raise RuntimeError("Source and project Python/platform must match")
        copy_packages(source["packages"], sysconfig.get_path("purelib"))
        current = probe(sys.executable)
        current["copied_from"] = source["source"]
    root = Path(sys.prefix)
    (root / "reused-torch.json").write_text(json.dumps(current, indent=2), encoding="utf-8")
    (root / "torch-constraints.txt").write_text(
        "".join(f"{name}=={version}\n" for name, version in sorted(current["packages"].items())
                if protected(name)), encoding="utf-8")
    print("Torch/CUDA checked locally. Protected versions saved to .venv-linux/torch-constraints.txt.")


if __name__ == "__main__":
    main()
